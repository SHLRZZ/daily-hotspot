def _reason_for(c):
    t = c["title"]
    for keys, txt in MANUAL:
        if all(k in t for k in keys):
            return txt

    seg = [CAT_REASON.get(c["category"], "")]
    for kws, txt in HOOKS:
        if any(k in t for k in kws):
            seg.append(txt)
            break
    if len(c["platforms"]) >= 3:
        seg.append("能同时上这么多平台，说明它是真正的公共事件，不是单一平台的算法推流。")
    return "".join(seg)


def explain(clusters, stats):
    """为每个话题补 reason，并输出类目整体归因。返回 category_analysis 列表。"""
    for c in clusters:
        c["reason"] = _reason_for(c)

    cat_rows = {r["category"]: r for r in stats["categories"]}
    # 每类取热度最高的话题作样例
    sample = {}
    for c in clusters:
        cat = c["category"]
        if cat not in sample or c["score"] > sample[cat]["score"]:
            sample[cat] = c

    # 找占比最高的类目，做一条结构性解释
    top_cat = stats["categories"][0]["category"] if stats["categories"] else None

    analysis = []
    for row in stats["categories"]:
        cat = row["category"]
        reason = CAT_REASON.get(cat, "")
        if cat == top_cat:
            reason += " 它排第一，更多是平台用户结构和算法偏好的结果——情绪类、明星类内容本来就在微博抖音 B站高频出现，并不代表今天出了多少大事。"
        if cat == "其他":
            reason += " 换句话说，年轻平台的热榜更“碎”，这也是当下注意力分散的一个侧面。"
        analysis.append({
            "category": cat,
            "count": row["count"],
            "share": row["share"],
            "reason": reason,
            "sample": sample[cat]["title"] if cat in sample else "",
        })
    return analysis
